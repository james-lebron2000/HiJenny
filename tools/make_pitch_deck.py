def to_pdf(pptx_path: Path) -> Path | None:
    soffice = shutil.which("soffice") or shutil.which("libreoffice")
    if not soffice:
        return None
    profile = Path(tempfile.mkdtemp(prefix="hijenny_lo_"))
    try:
        subprocess.run(
            [soffice, f"-env:UserInstallation=file://{profile}", "--headless",
             "--convert-to", "pdf", "--outdir", str(pptx_path.parent), str(pptx_path)],
            check=False, timeout=240, capture_output=True,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    pdf = pptx_path.with_suffix(".pdf")
    return pdf if pdf.is_file() and pdf.stat().st_size > 0 else None


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="docs/HiJenny_Pitch.pptx")
    parser.add_argument("--no-pdf", action="store_true")
    args = parser.parse_args()
    out = Path(args.out)
    build(out)
    print(f"wrote {out}")
    if not args.no_pdf:
        pdf = to_pdf(out)
        print(f"wrote {pdf}" if pdf else "PDF conversion skipped (LibreOffice not available)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
