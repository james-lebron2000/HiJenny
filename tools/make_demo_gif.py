def contact_sheet(frames: list[Image.Image], path: Path) -> None:
    picks = frames[:: max(1, len(frames) // 12)][:12]
    cols, rows = 4, 3
    tw, th = W // 4, H // 3
    sheet = Image.new("RGB", (tw * cols, th * rows), "white")
    for idx, frame in enumerate(picks):
        sheet.paste(frame.convert("RGB").resize((tw, th), Image.LANCZOS), ((idx % cols) * tw, (idx // cols) * th))
    sheet.save(path, quality=88)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", default="docs/assets")
    parser.add_argument("--frames-dir", default=None, help="keep generated frames here (debug)")
    args = parser.parse_args()

    required = [SHOTS / name for name in (
        "00_asset360.png", "02_projects.png", "04_evidence.png", "05_findings.png", "06_report.png",
    )]
    missing = [str(p) for p in required if not p.is_file()]
    if missing:
        raise SystemExit("missing screenshots (run tools/capture_screenshots.py first):\n" + "\n".join(missing))
    if not shutil.which("ffmpeg"):
        raise SystemExit("ffmpeg is required")

    out_dir = ROOT / args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    frames_dir = Path(args.frames_dir) if args.frames_dir else Path(tempfile.mkdtemp(prefix="hijenny_gif_"))
    frames_dir.mkdir(parents=True, exist_ok=True)

    frames: list[Image.Image] = []
    frames += intro_frames()
    # Start cursor near bottom-right of the projects page.
    frames += scene_frames(
        SHOTS / "02_projects.png", 0,
        "打开卖方资料包项目：13 份文档 / 284 页",
        "Open the seller package project — 13 documents, 284 pages",
        target=(0.975, 0.455), highlight_box=(0.93, 0.41, 0.998, 0.50),
        start=(0.80, 0.88), n_frames=15,
    )
    frames += scene_frames(
        SHOTS / "00_asset360.png", 1,
        "Asset 360：药物资产发现 + 资产评估一屏汇总",
        "Asset 360 — discovery and evaluation in one view (65/100 readiness)",
        target=(0.635, 0.655), highlight_box=(0.555, 0.585, 0.715, 0.705),
        start=(0.98, 0.44), n_frames=18,
    )
    frames += scene_frames(
        SHOTS / "04_evidence.png", 2,
        "点击 ORR 42.0% → CSR 第 11 页，原文逐字引用高亮",
        "Click ORR 42.0% → jump to CSR page 11 with the verbatim quote highlighted",
        target=(0.855, 0.66), highlight_box=(0.335, 0.355, 0.705, 0.455),
        start=(0.98, 0.60), n_frames=18,
    )
    frames += scene_frames(
        SHOTS / "05_findings.png", 3,
        "自动分类 A/B/C/U 与缺口，生成可发卖方的 6 条问题",
        "Type A/B/C/U and evidence gaps → 6 actionable seller questions",
        target=(0.48, 0.47), highlight_box=(0.05, 0.425, 0.955, 0.535),
        start=(0.95, 0.90), n_frames=17,
    )
    frames += scene_frames(
        SHOTS / "06_report.png", 4,
        "交付：Decision Brief + PDF/DOCX + 8-Sheet Excel",
        "Deliverables — Decision Brief, PDF/DOCX and an 8-sheet Excel workbook",
        target=(0.785, 0.112), highlight_box=(0.60, 0.075, 0.985, 0.165),
        start=(0.95, 0.42), n_frames=16,
    )
    frames += outro_frames()

    for idx, frame in enumerate(frames):
        frame.convert("RGB").save(frames_dir / f"frame_{idx:04d}.png", optimize=True)

    # Poster = first dashboard scene frame.
    poster = frames[12 + 15].convert("RGB")
    poster.save(OUT_POSTER, optimize=True)

    gif_cmd = [
        "ffmpeg", "-y", "-loglevel", "error", "-framerate", str(FPS),
        "-i", str(frames_dir / "frame_%04d.png"),
        "-vf", "split[s0][s1];[s0]palettegen=max_colors=128:stats_mode=diff[p];"
               "[s1][p]paletteuse=dither=bayer:bayer_scale=3:diff_mode=rectangle",
        "-loop", "0", str(OUT_GIF),
    ]
    subprocess.run(gif_cmd, check=True)
    mp4_cmd = [
        "ffmpeg", "-y", "-loglevel", "error", "-framerate", str(FPS),
        "-i", str(frames_dir / "frame_%04d.png"),
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "20", "-movflags", "+faststart",
        str(OUT_MP4),
    ]
    subprocess.run(mp4_cmd, check=True)
    contact_sheet(frames, out_dir / "demo_walkthrough_contact.png")

    if not args.frames_dir:
        shutil.rmtree(frames_dir, ignore_errors=True)
    print(f"frames: {len(frames)}  gif: {OUT_GIF.stat().st_size/1e6:.2f} MB  "
          f"mp4: {OUT_MP4.stat().st_size/1e6:.2f} MB  poster: {OUT_POSTER.stat().st_size/1e3:.0f} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
