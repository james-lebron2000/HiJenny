#!/usr/bin/env python3
"""Generate the HiJenny demo walkthrough GIF (+ MP4/poster) from real UI screenshots.

Usage:
    hijenny serve --port 8123                     # terminal 1 (demo workspace)
    python3 tools/make_demo_gif.py                # terminal 2
    python3 tools/make_demo_gif.py --check        # only validate inputs

Outputs:
    docs/assets/demo_walkthrough.gif   (README animated demo)
    docs/assets/demo_walkthrough.mp4   (higher-quality clip for slides)
    docs/assets/demo_walkthrough.png   (poster frame)

Requires Pillow + ffmpeg. Screenshots are generated by
tools/capture_screenshots.py from the running dashboard.
"""
from __future__ import annotations

import argparse
import math
import shutil
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SHOTS = ROOT / "docs/assets/screenshots"
OUT_GIF = ROOT / "docs/assets/demo_walkthrough.gif"
OUT_MP4 = ROOT / "docs/assets/demo_walkthrough.mp4"
OUT_POSTER = ROOT / "docs/assets/demo_walkthrough.png"

W, H = 1000, 680
TOP_H = 44
SHOT_W, SHOT_H = 920, 575
SHOT_X, SHOT_Y = 40, 48
CAP_Y = 632
FPS = 10

NAVY = (15, 39, 67)
NAVY_SOFT = (26, 55, 88)
BLUE = (46, 117, 182)
TEAL = (30, 125, 79)
AMBER = (154, 103, 0)
WHITE = (255, 255, 255)
MUTED = (138, 151, 168)
PANEL = (246, 249, 253)
LINE = (219, 226, 236)

CJK = "/System/Library/Fonts/PingFang.ttc"
CJK_ALT = "/System/Library/Fonts/STHeiti Medium.ttc"
EN = "/System/Library/Fonts/Supplemental/Arial Unicode.ttf"

STEPS = ["打开项目", "Asset 360", "回到原文", "发现与问题", "交付物"]
STEPS_EN = ["Project", "Discovery + Evaluation", "Trace to source", "Findings", "Deliverables"]


def font(size: int, cjk: bool = True) -> ImageFont.FreeTypeFont:
    size = int(round(size))
    for path in ((CJK if cjk else EN), CJK_ALT, EN):
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    return ImageFont.load_default()


def ease_out(t: float) -> float:
    t = max(0.0, min(1.0, t))
    return 1.0 - (1.0 - t) ** 3


def rounded(img: Image.Image, radius: int = 12) -> Image.Image:
    mask = Image.new("L", img.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, img.size[0] - 1, img.size[1] - 1], radius=radius, fill=255)
    out = img.convert("RGBA")
    out.putalpha(mask)
    return out


def draw_cursor(draw: ImageDraw.ImageDraw, x: float, y: float, scale: float = 1.0, pressed: bool = False) -> None:
    pts = [(0, 0), (0, 22), (6, 17), (11, 28), (15, 26), (10, 16), (18, 16)]
    pts = [(x + px * scale, y + py * scale) for px, py in pts]
    shadow = [(px + 2, py + 2) for px, py in pts]
    draw.polygon(shadow, fill=(0, 0, 0, 70))
    draw.polygon(pts, fill=(255, 255, 255, 255), outline=(15, 39, 67, 255))
    if pressed:
        draw.ellipse([x - 6, y - 6, x + 6, y + 6], outline=BLUE + (255,), width=2)


def click_ripple(base: Image.Image, x: float, y: float, progress: float) -> None:
    if progress <= 0 or progress >= 1:
        return
    overlay = Image.new("RGBA", base.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(overlay)
    radius = 6 + 34 * ease_out(progress)
    alpha = int(190 * (1 - progress))
    d.ellipse([x - radius, y - radius, x + radius, y + radius], outline=BLUE + (alpha,), width=2)
    base.alpha_composite(overlay)


def highlight(base: Image.Image, box: tuple[int, int, int, int], progress: float, color=BLUE) -> None:
    if progress <= 0:
        return
    x0, y0, x1, y1 = box
    pulse = 0.55 + 0.45 * (0.5 + 0.5 * math.sin(progress * math.pi * 2))
    overlay = Image.new("RGBA", base.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(overlay)
    d.rounded_rectangle(
        [x0, y0, x1, y1], radius=8,
        fill=color + (int(18 * pulse),),
        outline=color + (int(230 * pulse),), width=2,
    )
    base.alpha_composite(overlay)


def brand_bar(frame: Image.Image, step: int | None) -> None:
    d = ImageDraw.Draw(frame)
    d.rectangle([0, 0, W, TOP_H], fill=WHITE)
    d.line([0, TOP_H, W, TOP_H], fill=LINE, width=1)
    # logo mark
    d.rounded_rectangle([16, 9, 44, 35], radius=7, fill=NAVY)
    d.text((30, 22), "H", font=font(14), fill=WHITE, anchor="mm")
    d.text((54, 21), "HiJenny", font=font(17), fill=NAVY, anchor="lm")
    d.text((54, 34), "evidence-first due diligence", font=font(8, cjk=False), fill=MUTED, anchor="lm")
    if step is not None:
        label = f"STEP {step + 1}/5 · {STEPS[step]}"
        d.text((W - 22, 17), label, font=font(11), fill=NAVY, anchor="rm")
        d.text((W - 22, 31), STEPS_EN[step], font=font(8, cjk=False), fill=MUTED, anchor="rm")


def caption_bar(frame: Image.Image, step: int, zh: str, en: str) -> None:
    d = ImageDraw.Draw(frame)
    d.rectangle([0, CAP_Y, W, H], fill=NAVY)
    d.text((24, CAP_Y + 9), f"{step + 1}", font=font(13, cjk=False), fill=(127, 168, 232), anchor="lt")
    d.text((42, CAP_Y + 7), zh, font=font(15), fill=WHITE, anchor="lt")
    d.text((42, CAP_Y + 28), en, font=font(9.5, cjk=False), fill=(185, 203, 224), anchor="lt")
    # progress dots
    for i in range(5):
        cx = W - 24 - (4 - i) * 18
        if i == step:
            d.ellipse([cx - 4, CAP_Y + 22, cx + 4, CAP_Y + 30], fill=WHITE)
        else:
            d.ellipse([cx - 3, CAP_Y + 23, cx + 3, CAP_Y + 29], fill=(74, 104, 143))


def screenshot_frame(shot: Path | None, step: int, caption_zh: str, caption_en: str) -> Image.Image:
    frame = Image.new("RGBA", (W, H), (243, 245, 249, 255))
    if shot is not None:
        img = Image.open(shot).convert("RGB").resize((SHOT_W, SHOT_H), Image.LANCZOS).convert("RGBA")
        # soft shadow + border
        shadow = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        sd = ImageDraw.Draw(shadow)
        sd.rounded_rectangle([SHOT_X + 3, SHOT_Y + 5, SHOT_X + SHOT_W + 3, SHOT_Y + SHOT_H + 5],
                             radius=13, fill=(15, 39, 67, 50))
        shadow = shadow.filter(ImageFilter.GaussianBlur(5))
        frame.alpha_composite(shadow)
        frame.alpha_composite(rounded(img).copy(), (SHOT_X, SHOT_Y))
        d = ImageDraw.Draw(frame)
        d.rounded_rectangle([SHOT_X, SHOT_Y, SHOT_X + SHOT_W, SHOT_Y + SHOT_H], radius=12,
                            outline=(210, 219, 231, 255), width=1)
    brand_bar(frame, step)
    caption_bar(frame, step, caption_zh, caption_en)
    return frame


def scene_frames(shot: Path, step: int, caption_zh: str, caption_en: str,
                 target: tuple[float, float], highlight_box: tuple[float, float, float, float],
                 start: tuple[float, float], n_frames: int = 16, click: bool = True) -> list[Image.Image]:
    frames: list[Image.Image] = []
    target_px = (SHOT_X + target[0] * SHOT_W, SHOT_Y + target[1] * SHOT_H)
    box = (
        int(SHOT_X + highlight_box[0] * SHOT_W),
        int(SHOT_Y + highlight_box[1] * SHOT_H),
        int(SHOT_X + highlight_box[2] * SHOT_W),
        int(SHOT_Y + highlight_box[3] * SHOT_H),
    )
    for i in range(n_frames):
        t = i / max(1, n_frames - 1)
        frame = screenshot_frame(shot, step, caption_zh, caption_en)
        # cursor moves in during first 45% of the scene, then clicks
        move = ease_out(min(1.0, t / 0.45))
        cx = start[0] + (target_px[0] - start[0]) * move
        cy = start[1] + (target_px[1] - start[1]) * move
        click_progress = 0.0
        if click and t >= 0.45:
            click_progress = min(1.0, (t - 0.45) / 0.12)
        if t >= 0.35:
            highlight(frame, box, min(1.0, (t - 0.35) / 0.15))
        if click and t >= 0.45:
            click_ripple(frame, target_px[0], target_px[1], click_progress)
        overlay = Image.new("RGBA", frame.size, (0, 0, 0, 0))
        draw_cursor(ImageDraw.Draw(overlay), cx, cy, scale=1.15, pressed=0.45 <= t <= 0.58)
        frame.alpha_composite(overlay)
        frames.append(frame)
    return frames


def gradient_bg() -> Image.Image:
    bg = Image.new("RGBA", (W, H), NAVY + (255,))
    d = ImageDraw.Draw(bg)
    for y in range(H):
        k = y / H
        color = (
            int(15 + 10 * k),
            int(39 + 18 * k),
            int(67 + 28 * k),
        )
        d.line([0, y, W, y], fill=color + (255,))
    d.rectangle([0, 0, 6, H], fill=BLUE)
    return bg


def intro_frames() -> list[Image.Image]:
    frames: list[Image.Image] = []
    n = 12
    for i in range(n):
        t = i / (n - 1)
        bg = gradient_bg()
        d = ImageDraw.Draw(bg)
        d.text((64, 214), "HIJENNY · AI-NATIVE DUE DILIGENCE", font=font(11, cjk=False), fill=(127, 168, 232), anchor="lt")
        d.text((62, 240), "HiJenny", font=font(62, cjk=False), fill=WHITE, anchor="lt")
        d.text((64, 318), "医药资产交易智能尽调系统", font=font(24), fill=WHITE, anchor="lt")
        d.text((64, 360), "把卖方资料包变成可溯源、可评估、可发卖方的问题清单", font=font(12), fill=(185, 203, 224), anchor="lt")
        # 5-step chips
        labels = ["1 打开项目", "2 Asset 360", "3 回到原文", "4 发现与问题", "5 交付物"]
        x = 64
        for idx, label in enumerate(labels):
            width = 132 if idx != 1 else 148
            d.rounded_rectangle([x, 430, x + width, 466], radius=18, outline=(74, 104, 143), width=1)
            d.text((x + width / 2, 448), label, font=font(11), fill=(216, 228, 242), anchor="mm")
            x += width + 10
        d.text((64, 536), "DEMO WALKTHROUGH · 10s · synthetic Phase 2 package", font=font(10, cjk=False),
               fill=(122, 141, 165), anchor="lt")
        # progress line
        d.rectangle([64, 572, 64 + int((W - 128) * (0.15 + 0.5 * t)), 574], fill=BLUE)
        frames.append(bg)
    return frames


